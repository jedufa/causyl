"""infra.controlplane.job_registry

Durable job registry for long-running tooling processes (manifest runner).

Why this exists
---------------
The WebUI can launch a manifest runner (which itself launches many runs). Humans
then, predictably, want a Stop button. A Stop button needs:

- a durable record of "what PID/PGID did we launch?"
- restart-safe reconciliation (server restarts should not lose control)
- an auditable stop request artifact

This module stores one JSON record per job under:
  <repo_root>/runtime/state/control/manifest_jobs/<job_id>.json

It also supports STOP/PAUSE sentinels under the manifest report directory:
  <report_dir>/.control/STOP
  <report_dir>/.control/PAUSE

The sentinels are treated as audit artifacts. STOP is never auto-removed.

"""

from __future__ import annotations

import json
import os
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from infra.controlplane.constants import (
    MANIFEST_JOBS_DIR_REL,
    MANIFEST_REPORT_CONTROL_DIRNAME,
    PAUSE_SENTINEL_NAME,
    STOP_SENTINEL_NAME,
)


def _strip_yaml_scalar(s: str) -> str:
    """Best-effort YAML scalar cleanup.

    We deliberately avoid a hard dependency on a YAML library here.
    Manifests are generated by our own tooling and the values we care about
    (paths) are typically plain scalars.
    """
    x = str(s or "").strip()
    if (len(x) >= 2) and ((x[0] == x[-1]) and x[0] in {"'", '"'}):
        x = x[1:-1]
    return x.strip()


def _infer_report_dir_from_manifest(manifest_path: str, cwd: str = "") -> str:
    """Infer report_dir from a manifest YAML file (best-effort).

    The WebUI launcher may start the manifest runner without an explicit
    --report_dir. In that case, the runner typically uses the report directory
    declared in the manifest.

    We keep this intentionally simple and resilient:
    - read a limited prefix of the YAML text
    - search for common scalar keys

    Returns empty string if it cannot be inferred.
    """
    mp_raw = str(manifest_path or "").strip()
    if not mp_raw:
        return ""
    try:
        mp = Path(mp_raw)
        if not mp.is_absolute():
            base = Path(cwd or os.getcwd())
            mp = (base / mp).resolve()
        if (not mp.exists()) or (not mp.is_file()) or mp.is_symlink():
            return ""

        txt = mp.read_text(encoding="utf-8", errors="replace")
        lines = txt.splitlines()[:400]
        keys = (
            "report_dir",
            "report_root",
            "output_dir",
            "out_dir",
        )
        for ln in lines:
            s = ln.strip()
            if (not s) or s.startswith("#"):
                continue
            for k in keys:
                if s.startswith(k + ":"):
                    val = s.split(":", 1)[1].strip()
                    return _strip_yaml_scalar(val)
    except Exception:
        return ""
    return ""


def _maybe_infer_report_dir(job: Dict[str, Any]) -> Dict[str, Any]:
    """If job lacks report_dir, try to infer it from the manifest path."""
    j = dict(job or {})
    if str(j.get("report_dir") or "").strip():
        return j
    manifest_path = str(j.get("manifest") or "").strip()
    cwd = str(j.get("cwd") or "").strip()
    inferred = _infer_report_dir_from_manifest(manifest_path, cwd=cwd)
    if inferred:
        j["report_dir"] = inferred
    return j


def _now_utc_iso() -> str:
    """Return current UTC time in ISO-8601 (seconds resolution)."""
    import datetime as _dt

    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _atomic_write_json(path: Path, obj: Dict[str, Any]) -> None:
    """Atomically write JSON to disk (tmp + os.replace)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    data = (json.dumps(obj, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")
    with open(tmp, "wb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def _pid_alive(pid: int) -> bool:
    """Return True if pid exists (Linux/WSL)."""
    if pid <= 0:
        return False
    try:
        return Path(f"/proc/{int(pid)}").exists()
    except Exception:
        return False


def _pid_cmdline(pid: int) -> str:
    """Return process cmdline text for a pid (best-effort)."""
    if pid <= 0:
        return ""
    try:
        p = Path(f"/proc/{int(pid)}/cmdline")
        if (not p.exists()) or (not p.is_file()) or p.is_symlink():
            return ""
        raw = p.read_bytes()
        if not raw:
            return ""
        return raw.replace(b"\x00", b" ").decode("utf-8", errors="replace").strip()
    except Exception:
        return ""


def _pid_matches_job(pid: int, job: Dict[str, Any]) -> bool:
    """Best-effort guard against PID reuse causing false RUNNING states."""
    cmd = _pid_cmdline(int(pid))
    if not cmd:
        return False
    lo = cmd.lower()
    markers: List[str] = []
    for k in (
        "job_id",
        "launch_target_module",
        "selected_target",
    ):
        v = str(job.get(k) or "").strip()
        if v:
            markers.append(v.lower())
    # Effective command tokens are very strong markers when present.
    eff = job.get("effective_cmd")
    if isinstance(eff, list):
        for tok in eff:
            t = str(tok or "").strip()
            if t and len(t) >= 8:
                markers.append(t.lower())
    if not markers:
        # With no markers, fall back to existing liveness behavior.
        return True
    # Match-any is deliberate; exact-all would be too brittle across wrappers.
    return any(m in lo for m in markers)


def _safe_int(x: Any, default: int = 0) -> int:
    try:
        return int(x)
    except Exception:
        return int(default)


def manifest_jobs_dir(runs_root: Path) -> Path:
    """Return the durable manifest jobs directory under runtime/state/control.

    The runs_root argument is retained for API compatibility with existing call sites.
    """
    _ = runs_root
    repo_root = Path(__file__).resolve().parents[2]
    return (repo_root / "runtime" / "state" / "control" / "manifest_jobs").resolve()


def manifest_job_path(runs_root: Path, job_id: str) -> Path:
    """Return path to the durable job JSON file for job_id."""
    jid = str(job_id or "").strip()
    if not jid:
        raise ValueError("job_id required")
    return manifest_jobs_dir(runs_root) / f"{jid}.json"


def new_job_id(prefix: str = "mjob") -> str:
    """Generate a new job id."""
    return f"{prefix}_{uuid.uuid4().hex[:12]}"


def load_job(runs_root: Path, job_id: str) -> Optional[Dict[str, Any]]:
    """Load a job record; return None if missing/unreadable."""
    p = manifest_job_path(runs_root, job_id)
    try:
        if not p.exists() or not p.is_file() or p.is_symlink():
            return None
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None


def write_job(runs_root: Path, job: Dict[str, Any]) -> None:
    """Write a job record (atomic)."""
    jid = str(job.get("job_id") or "").strip()
    if not jid:
        raise ValueError("job.job_id required")
    p = manifest_job_path(runs_root, jid)
    _atomic_write_json(p, job)


def list_jobs(runs_root: Path) -> List[Dict[str, Any]]:
    """List all durable manifest job records (best-effort)."""
    base = manifest_jobs_dir(runs_root)
    out: List[Dict[str, Any]] = []
    if not base.exists() or not base.is_dir():
        return out
    for p in sorted(base.glob("*.json"), key=lambda x: x.name):
        try:
            if not p.is_file() or p.is_symlink():
                continue
            obj = json.loads(p.read_text(encoding="utf-8"))
            if isinstance(obj, dict):
                out.append(obj)
        except Exception:
            continue
    return out


def reconcile_job(job: Dict[str, Any]) -> Dict[str, Any]:
    """Reconcile liveness of a job record (PID/PGID existence)."""
    j = _maybe_infer_report_dir(dict(job or {}))
    pid = _safe_int(j.get("pid"), 0)
    alive = _pid_alive(pid)
    if alive and (pid > 0):
        # Prevent stale "RUNNING" when the PID now belongs to an unrelated process.
        if not _pid_matches_job(pid, j):
            alive = False
    state = str(j.get("state") or "RUNNING").upper()

    # If process is gone, mark STOPPED unless already terminal.
    if not alive and state in {"RUNNING", "STOP_REQUESTED", "STOPPING", "PAUSED"}:
        j["state"] = "STOPPED"
        j["ended_at_utc"] = j.get("ended_at_utc") or _now_utc_iso()

    # Mark last_seen for UI sorting.
    j["last_seen_utc"] = _now_utc_iso()
    j["pid_alive"] = bool(alive)
    return j


def reconcile_all(runs_root: Path) -> List[Dict[str, Any]]:
    """Load + reconcile all job records; writes back state updates if needed."""
    jobs = list_jobs(runs_root)
    out: List[Dict[str, Any]] = []
    for j in jobs:
        r = reconcile_job(j)
        out.append(r)
        # Persist reconciliation if state changed.
        try:
            if (str(r.get("state")) != str(j.get("state"))) or (bool(r.get("pid_alive")) != bool(j.get("pid_alive"))):
                write_job(runs_root, r)
        except Exception:
            pass
    # Sort newest-first by created_at_utc (fallback by file order).
    def _ts(x: Dict[str, Any]) -> float:
        try:
            import datetime as _dt

            s = str(x.get("created_at_utc") or "").replace("Z", "+00:00")
            return _dt.datetime.fromisoformat(s).timestamp()
        except Exception:
            return 0.0

    out.sort(key=_ts, reverse=True)
    return out


def report_control_dir(report_dir: Path) -> Path:
    """Return the .control directory within a report_dir."""
    return (Path(report_dir) / MANIFEST_REPORT_CONTROL_DIRNAME).resolve()


def stop_sentinel_path(report_dir: Path) -> Path:
    """Return STOP sentinel path for a report directory."""
    return report_control_dir(report_dir) / STOP_SENTINEL_NAME


def pause_sentinel_path(report_dir: Path) -> Path:
    """Return PAUSE sentinel path for a report directory."""
    return report_control_dir(report_dir) / PAUSE_SENTINEL_NAME


def write_stop_sentinel(report_dir: Path, *, mode: str, requested_by: str = "webui", reason: str = "") -> Path:
    """Write STOP sentinel (audit artifact)."""
    d = report_control_dir(report_dir)
    d.mkdir(parents=True, exist_ok=True)
    p = stop_sentinel_path(report_dir)
    payload = {
        "schema_version": "manifest_stop_v1",
        "requested_at_utc": _now_utc_iso(),
        "requested_by": str(requested_by or "webui"),
        "mode": str(mode or "graceful"),
        "reason": str(reason or ""),
    }
    _atomic_write_json(p, payload)
    return p


def write_pause_sentinel(report_dir: Path, *, requested_by: str = "webui", reason: str = "") -> Path:
    """Write PAUSE sentinel."""
    d = report_control_dir(report_dir)
    d.mkdir(parents=True, exist_ok=True)
    p = pause_sentinel_path(report_dir)
    payload = {
        "schema_version": "manifest_pause_v1",
        "requested_at_utc": _now_utc_iso(),
        "requested_by": str(requested_by or "webui"),
        "reason": str(reason or ""),
    }
    _atomic_write_json(p, payload)
    return p


def remove_pause_sentinel(report_dir: Path) -> bool:
    """Remove PAUSE sentinel (resume)."""
    p = pause_sentinel_path(report_dir)
    try:
        if p.exists():
            p.unlink()
            return True
    except Exception:
        return False
    return False
